"""Write the app's official subject list from an ingested master index.

    python3 tools/ingest/export_syllabus.py content/build/army_jd_jw_2025_part1/index.json \
        --name armyJunior --out app/lib/data/syllabus/army_junior.dart

Only the table of contents goes into the app (codes, subject names, periods,
page numbers); the précis text itself stays out of the repository.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def dart_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("index", type=Path)
    ap.add_argument("--name", required=True, help="Dart constant name, e.g. armyJunior")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    data = json.loads(args.index.read_text())
    doc, groups = data["document"], data["groups"]
    lines = [
        "// GENERATED by tools/ingest/export_syllabus.py from the DGNCC précis master index.",
        "// Do not edit by hand; re-run the exporter after ingesting a new edition.",
        "",
        "import 'syllabus.dart';",
        "",
        f"const {args.name} = Syllabus(",
        f"  source: {dart_str(doc['title'] + ' · DGNCC Précis' + (' ' + doc['edition'] if doc['edition'] else ''))},",
        "  official: true,",
        "  groups: [",
    ]
    for code, name in groups.items():
        subjects = [s for s in data["subjects"] if s["code"].rsplit("-", 1)[0] == code]
        lines.append(f"    SubjectGroup(code: {dart_str(code)}, name: {dart_str(name)}, subjects: [")
        for s in subjects:
            lines.append(
                f"      SyllabusSubject(code: {dart_str(s['code'])}, title: {dart_str(s['title'])}, "
                f"theoryPeriods: {s['theory_periods']}, practicalPeriods: {s['practical_periods']}, "
                f"page: {s['book_page']}),"
            )
        lines.append("    ]),")
    lines += ["  ],", ");", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    print(f"Wrote {args.out}: {len(groups)} groups, {len(data['subjects'])} subjects")


if __name__ == "__main__":
    main()
