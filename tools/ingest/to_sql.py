"""Write a SQL script that loads an ingested précis into Supabase.

    python3 tools/ingest/to_sql.py content/build/army_jd_jw_2025_part1

Writes content/build/<name>/load.sql (git-ignored). Paste it into the
Supabase SQL Editor, which runs as the database owner, so no secret key ever
leaves your dashboard. Re-running it replaces the earlier load of the same
document. Questions go in as drafts in the shared bank, hidden from cadets
until an answer is set and they are approved.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

TAG = "$phx$"


def q(value) -> str:
    """Quote a value as a SQL literal using dollar quoting."""
    if value is None:
        return "null"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value)
    if TAG in text:
        raise ValueError(f"text contains the quoting tag {TAG}")
    return f"{TAG}{text}{TAG}"


def q_array(values: list[str]) -> str:
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]"


def build_sql(index: dict, passages: list[dict], questions: list[dict]) -> str:
    doc = index["document"]
    title = f"{doc['title']} ({doc['edition']})" if doc.get("edition") else doc["title"]
    source = doc["source_file"]
    out = [
        f"-- Phoenix knowledge base load: {title}, from {source}",
        "-- Generated by tools/ingest/to_sql.py. Contains DGNCC précis text: do not commit or share.",
        "begin;",
        "",
        "-- Replace any earlier load of this document.",
        f"delete from questions where unit_id is null and source_chunk_id is null and subject = {q(title)};",
        f"delete from documents where unit_id is null and storage_path = {q('precis/' + source)};",
        "",
        "with doc as (",
        "  insert into documents (unit_id, title, subject, wing, division_level, storage_path)",
        f"  values (null, {q(title)}, null, {q(doc['wing']) + '::wing' if doc['wing'] != 'common' else 'null'}, "
        f"{q(doc['level'])}, {q('precis/' + source)})",
        "  returning id",
        ")",
        "insert into document_chunks (document_id, page, page_end, heading, content)",
        "select doc.id, v.page, v.page_end, v.heading, v.content from doc, (values",
    ]
    rows = []
    for p in passages:
        pages = p["book_pages"] or [None]
        first, last = pages[0], pages[-1]
        heading = f"{p['chapter_code']} · {p['chapter_title']} · {p['section']}"
        rows.append(f"  ({q(first)}::smallint, {q(last if last != first else None)}::smallint, "
                    f"{q(heading)}, {q(p['text'])})")
    out.append(",\n".join(rows))
    out.append(") as v(page, page_end, heading, content);")
    out.append("")
    if questions:
        out.append("insert into questions (unit_id, subject, wing, prompt, options, correct_index, explanation, "
                   "status, source_page) values")
        qrows = []
        for item in questions:
            wing = f"{q(doc['wing'])}::wing" if doc["wing"] != "common" else "null"
            qrows.append(f"  (null, {q(title)}, {wing}, {q(item['prompt'])}, {q_array(item['options'])}, "
                         f"null, {q(item['chapter_code'] + ' · Q' + str(item['number']))}, 'draft', "
                         f"{q(item['book_page'])})")
        out.append(",\n".join(qrows) + ";")
        out.append("")
    out += [
        "commit;",
        "",
        "-- Check: counts for this document.",
        "select d.title, (select count(*) from document_chunks c where c.document_id = d.id) as passages,",
        f"       (select count(*) from questions where subject = {q(title)} and status = 'draft') as draft_questions",
        f"from documents d where d.storage_path = {q('precis/' + source)};",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("build_dir", type=Path)
    args = ap.parse_args()
    index = json.loads((args.build_dir / "index.json").read_text())
    passages = [json.loads(l) for l in (args.build_dir / "passages.jsonl").open()]
    questions = [json.loads(l) for l in (args.build_dir / "questions.jsonl").open()]
    out = args.build_dir / "load.sql"
    out.write_text(build_sql(index, passages, questions))
    print(f"Wrote {out}: {len(passages)} passages, {len(questions)} draft questions")


if __name__ == "__main__":
    main()
